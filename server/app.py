"""
文化产品价值失范综合预警平台 —— 最小后端（里程碑 1）
============================================================

【为什么要写后端？】
前端（HTML/CSS/JS）跑在浏览器里，它只能"显示"。
真正能读写数据库、调用大模型、判断权限的代码，必须跑在服务器上，
通过 HTTP 接口对外提供能力 —— 那个程序就叫后端。

【这个文件只做三件事】
  1. 启动一个 HTTP 服务，监听本机 5000 端口
  2. 暴露两个接口：/api/health（健康检查）、/api/alerts（预警列表）
  3. 留了一个开关，专门用来复现"跨域（CORS）"这个最常见的 bug

【怎么跑】
  cd D:\\culture-platform\\server
  .venv\\Scripts\\python.exe app.py
  然后浏览器访问 http://127.0.0.1:5000/api/health 应该看到 JSON
"""

import os

from flask import Flask, jsonify

app = Flask(__name__)


# ============================================================
#  ★★★ 这节课的关键开关 ★★★
# ------------------------------------------------------------
# 先让它保持 False，把前后端都跑起来、点页面上的按钮，
# 去浏览器 F12 的 Console 看会报什么错 —— 记住那个红色报错，
# 它长得像这样：
#   Access to fetch at 'http://127.0.0.1:5000/api/health'
#   from origin 'http://127.0.0.1:5500' has been blocked by CORS policy
#
# 然后把 False 改成 True，重启后端，再点一次按钮 —— 问题就消失了。
# 一行代码修掉一个 bug，你现在就体验到了。
# ============================================================
ENABLE_CORS = True

if ENABLE_CORS:
    # flask_cors 做的事其实很简单：给每个响应自动加上这几个头
    #   Access-Control-Allow-Origin: *
    #   Access-Control-Allow-Methods: GET, POST, ...
    #   Access-Control-Allow-Headers: Content-Type, ...
    # 浏览器看到这些头，才肯把响应交给页面的 JS。
    # 用这个库是图省事，你也可以自己写 after_request 手动加。
    from flask_cors import CORS

    CORS(app)


# ============================================================
#  假数据：先用写死的数据把链路跑通，后面再接真实数据库
#  （这是很实用的开发策略：先打通"能显示"，再换成"真数据"）
# ============================================================
