# ============================================================
#  接口 0：根路径
# ------------------------------------------------------------
#  为什么需要它？
#  部署完成后，人的第一反应是访问网站根路径 http://xxx.com/。
#  如果没定义这个路由，会返回 404 —— 虽然这其实反而说明服务是活的，
#  但看到 404 的人（你自己、你老师、任何同事）都容易误以为部署失败了。
#  加一个说明页，既避免误会，也顺便充当「服务活着吗」的指示灯。
# ============================================================
@app.get("/")
def index():
    return jsonify(
        service="文化产品价值失范综合预警平台 API",
        version="0.1.0",
        status="running",
        endpoints={
            "/api/health": "健康检查",
            "/api/alerts": "预警列表",
        },
    )


# ============================================================
#  接口 1：健康检查
# ------------------------------------------------------------
#  部署时这个接口特别重要。它是你排查故障的第一站：
#  在服务器上执行 curl http://127.0.0.1:5000/api/health
#    · 有返回 → 后端活着，故障在 nginx 那一层
#    · 没返回 → 后端死了或没起来，跟 nginx 无关
# ============================================================
@app.get("/api/health")
def health():
    return jsonify(ok=True, service="alert-platform", version="0.1.0")


# ============================================================
#  接口 2：返回预警列表
# ------------------------------------------------------------
#  @app.get("路径") 是 Flask 的装饰器写法：
#  意思是「当有人用 GET 方法访问这个路径时，执行下面这个函数，
#  并把函数返回的内容作为 HTTP 响应发回去」。
#
#  jsonify() 会把 Python 字典自动转成 JSON 字符串，
#  并自动设置 Content-Type: application/json。
# ============================================================
@app.get("/api/alerts")
def list_alerts():
    return jsonify(total=len(ALERTS), items=ALERTS)


# ============================================================
#  启动入口
# ------------------------------------------------------------
#  下面这两行是「部署时最容易踩的两个坑」，现在就按正确姿势写好，
#  免得以后上服务器时对着 502 发呆半天。
#
#  ★ 坑 1：host 不能写 127.0.0.1
#     127.0.0.1 表示「只有本机能连」。部署到服务器后，
#     从外网来的请求根本到不了你的进程，页面永远打不开。
#     0.0.0.0 表示「任何来源都可以连」。
#
#  ★ 坑 2：端口不能写死
#     云平台（Render / Railway / Fly.io 等）会通过 PORT 环境变量
#     告诉你「该监听哪个端口」。你要是写死 5000，
#     平台把流量打到它指定的端口，你的服务却在 5000 上干等 ——
#     外部看到的就是 502 Bad Gateway。
#
#  debug=True 开发时很方便（改代码自动重启 + 详细报错），
#  但绝不能用在生产环境：它会向访问者暴露源码路径和内部变量。
# ============================================================
if __name__ == "__main__":
    port = int(os.environ.get("PORT", 5000))

    # ------------------------------------------------------------
    #  ★ 自动重载开关（专治「改了代码忘了重启」）★
    # ------------------------------------------------------------
    # debug=True 时 Flask 会监视代码文件，一改动就自动重启进程。
    # 打开它之后，你改完 app.py 保存，服务会自己重启，
    # 再也不会出现「改了却看不到效果」这种问题。
    #
    # 想关掉自动重载、模拟生产环境的行为，这样启动：
    #     $env:FLASK_DEBUG="0"; .venv\Scripts\python.exe app.py
    #
    # 为什么线上不怕 debug 泄露信息？
    # 因为部署到 Render 时是用 gunicorn 启动的，
    # gunicorn 只会 import 这个模块里的 app 对象，
    # 下面这段 __main__ 代码根本不会被执行。
    # ------------------------------------------------------------
    debug_mode = os.environ.get("FLASK_DEBUG", "1") != "0"

    app.run(host="0.0.0.0", port=port, debug=debug_mode)
